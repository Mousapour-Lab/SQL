-- Factory maintenance practice schema (Oracle SQL, 12c or later).
-- Run this script first, then run seed_data.sql.
--
-- If the tables already exist, run these four lines first (child tables first):
-- DROP TABLE maintenance_requests PURGE;
-- DROP TABLE equipment PURGE;
-- DROP TABLE employees PURGE;
-- DROP TABLE departments PURGE;

-- Departments of the factory.
CREATE TABLE departments (
    department_id   NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    department_name VARCHAR2(60) NOT NULL UNIQUE,
    location        VARCHAR2(60)
);

-- Employees who work in a department.
CREATE TABLE employees (
    employee_id   NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name    VARCHAR2(40) NOT NULL,
    last_name     VARCHAR2(40) NOT NULL,
    job_title     VARCHAR2(40),
    salary        NUMBER(10, 2),
    hire_date     DATE NOT NULL,
    department_id NUMBER,
    CONSTRAINT fk_employees_department
        FOREIGN KEY (department_id) REFERENCES departments (department_id)
);

-- Machines, vehicles and other equipment owned by a department.
CREATE TABLE equipment (
    equipment_id   NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    equipment_name VARCHAR2(60) NOT NULL,
    equipment_type VARCHAR2(40),
    purchase_date  DATE,
    status         VARCHAR2(20) DEFAULT 'OPERATIONAL' NOT NULL,
    department_id  NUMBER,
    CONSTRAINT fk_equipment_department
        FOREIGN KEY (department_id) REFERENCES departments (department_id),
    CONSTRAINT ck_equipment_status
        CHECK (status IN ('OPERATIONAL', 'NEEDS_REPAIR', 'OUT_OF_SERVICE'))
);

-- Repair requests: one employee asks for work on one piece of equipment.
CREATE TABLE maintenance_requests (
    request_id   NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    equipment_id NUMBER NOT NULL,
    employee_id  NUMBER NOT NULL,
    request_date DATE DEFAULT SYSDATE NOT NULL,
    status       VARCHAR2(20) DEFAULT 'OPEN' NOT NULL,
    description  VARCHAR2(200),
    closed_date  DATE,
    CONSTRAINT fk_requests_equipment
        FOREIGN KEY (equipment_id) REFERENCES equipment (equipment_id),
    CONSTRAINT fk_requests_employee
        FOREIGN KEY (employee_id) REFERENCES employees (employee_id),
    CONSTRAINT ck_requests_status
        CHECK (status IN ('OPEN', 'IN_PROGRESS', 'CLOSED'))
);
