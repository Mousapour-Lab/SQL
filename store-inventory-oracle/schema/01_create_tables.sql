-- 01_create_tables.sql
-- Five tables for a small store: who supplies us, what we sell, what we ordered,
-- and every change of stock.
-- Target: Oracle 19c. Identity columns need 12c or later.

-- Suppliers we buy from.
CREATE TABLE suppliers (
    supplier_id   NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    supplier_name VARCHAR2(80) NOT NULL,
    contact_name  VARCHAR2(60),
    phone         VARCHAR2(30),
    email         VARCHAR2(80),
    is_active     CHAR(1) DEFAULT 'Y' NOT NULL,
    CONSTRAINT uq_suppliers_name UNIQUE (supplier_name),
    CONSTRAINT ck_suppliers_active CHECK (is_active IN ('Y', 'N'))
);

-- Items we keep in stock. quantity_on_hand is maintained by a trigger,
-- so it is never typed in by hand.
CREATE TABLE items (
    item_id          NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku              VARCHAR2(20) NOT NULL,
    item_name        VARCHAR2(80) NOT NULL,
    supplier_id      NUMBER,
    unit_price       NUMBER(10, 2) NOT NULL,
    quantity_on_hand NUMBER(10) DEFAULT 0 NOT NULL,
    reorder_point    NUMBER(10) DEFAULT 0 NOT NULL,
    updated_at       DATE,
    CONSTRAINT uq_items_sku UNIQUE (sku),
    CONSTRAINT fk_items_supplier
        FOREIGN KEY (supplier_id) REFERENCES suppliers (supplier_id),
    -- Stock can reach zero but never below it.
    CONSTRAINT ck_items_qty CHECK (quantity_on_hand >= 0),
    CONSTRAINT ck_items_reorder CHECK (reorder_point >= 0),
    CONSTRAINT ck_items_price CHECK (unit_price >= 0)
);

-- Purchase orders: one row per order sent to one supplier.
CREATE TABLE purchase_orders (
    po_id       NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    supplier_id NUMBER NOT NULL,
    order_date  DATE DEFAULT SYSDATE NOT NULL,
    status      VARCHAR2(20) DEFAULT 'DRAFT' NOT NULL,
    notes       VARCHAR2(200),
    CONSTRAINT fk_po_supplier
        FOREIGN KEY (supplier_id) REFERENCES suppliers (supplier_id),
    CONSTRAINT ck_po_status
        CHECK (status IN ('DRAFT', 'ORDERED', 'RECEIVED', 'CANCELLED'))
);

-- The lines of a purchase order: which item, how many, at what price.
-- unit_price is copied here because a price can change later.
CREATE TABLE purchase_order_lines (
    line_id    NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    po_id      NUMBER NOT NULL,
    item_id    NUMBER NOT NULL,
    quantity   NUMBER(10) NOT NULL,
    unit_price NUMBER(10, 2) NOT NULL,
    CONSTRAINT fk_pol_po
        FOREIGN KEY (po_id) REFERENCES purchase_orders (po_id),
    CONSTRAINT fk_pol_item
        FOREIGN KEY (item_id) REFERENCES items (item_id),
    CONSTRAINT uq_pol_po_item UNIQUE (po_id, item_id),
    CONSTRAINT ck_pol_qty CHECK (quantity > 0),
    CONSTRAINT ck_pol_price CHECK (unit_price >= 0)
);

-- Every IN and OUT of the warehouse. This table is the history; the stock
-- number on items is only the result of it.
CREATE TABLE stock_movements (
    movement_id   NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    item_id       NUMBER NOT NULL,
    movement_type VARCHAR2(3) NOT NULL,
    quantity      NUMBER(10) NOT NULL,
    movement_date DATE DEFAULT SYSDATE NOT NULL,
    reason        VARCHAR2(120),
    po_id         NUMBER,
    CONSTRAINT fk_sm_item
        FOREIGN KEY (item_id) REFERENCES items (item_id),
    CONSTRAINT fk_sm_po
        FOREIGN KEY (po_id) REFERENCES purchase_orders (po_id),
    CONSTRAINT ck_sm_type CHECK (movement_type IN ('IN', 'OUT')),
    -- quantity is always positive; the direction is movement_type.
    CONSTRAINT ck_sm_qty CHECK (quantity > 0)
);
